-- AI & Firecrawl metering: usage log, shared response cache and a daily budget.
-- Written to by edge functions (service role) through _shared/metered.ts.

CREATE TABLE IF NOT EXISTS public.ai_usage_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  fn text NOT NULL,
  provider text NOT NULL,
  endpoint text,
  model text,
  status integer,
  cached boolean NOT NULL DEFAULT false,
  blocked boolean NOT NULL DEFAULT false,
  prompt_tokens integer,
  completion_tokens integer,
  duration_ms integer
);

CREATE INDEX IF NOT EXISTS ai_usage_log_provider_day_idx
  ON public.ai_usage_log (provider, created_at DESC) WHERE cached = false AND blocked = false;
CREATE INDEX IF NOT EXISTS ai_usage_log_fn_idx ON public.ai_usage_log (fn, created_at DESC);

-- Edge functions (service role) write; signed-in users may read, but the
-- RLS policy below limits rows to admins. Anonymous users get nothing.
REVOKE ALL ON public.ai_usage_log FROM anon, authenticated;
GRANT SELECT ON public.ai_usage_log TO authenticated;
GRANT ALL ON public.ai_usage_log TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.ai_usage_log_id_seq TO service_role;

ALTER TABLE public.ai_usage_log ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Admins read ai usage" ON public.ai_usage_log;
CREATE POLICY "Admins read ai usage"
  ON public.ai_usage_log FOR SELECT
  USING ((SELECT public.is_admin(auth.uid())));

CREATE TABLE IF NOT EXISTS public.provider_cache (
  key text PRIMARY KEY,
  fn text,
  provider text NOT NULL,
  endpoint text,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS provider_cache_expires_idx ON public.provider_cache (expires_at);

-- Only the service role (edge functions) reads or writes the cache.
REVOKE ALL ON public.provider_cache FROM anon, authenticated;
GRANT ALL ON public.provider_cache TO service_role;

ALTER TABLE public.provider_cache ENABLE ROW LEVEL SECURITY;
-- No policies, by design.

INSERT INTO public.platform_config (key, value)
VALUES ('ai_budget', '{"enabled": true, "daily_ai_calls": 600, "daily_firecrawl_calls": 300}'::jsonb)
ON CONFLICT (key) DO NOTHING;

-- Daily summary for the admin AI usage panel.
CREATE OR REPLACE FUNCTION public.ai_usage_summary(_days integer DEFAULT 14)
RETURNS TABLE (
  day date,
  fn text,
  provider text,
  calls bigint,
  cached bigint,
  blocked bigint,
  failed bigint,
  prompt_tokens bigint,
  completion_tokens bigint
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    (l.created_at AT TIME ZONE 'UTC')::date AS day,
    l.fn,
    l.provider,
    count(*) FILTER (WHERE NOT l.cached AND NOT l.blocked) AS calls,
    count(*) FILTER (WHERE l.cached) AS cached,
    count(*) FILTER (WHERE l.blocked) AS blocked,
    count(*) FILTER (WHERE NOT l.cached AND NOT l.blocked AND l.status >= 400) AS failed,
    coalesce(sum(l.prompt_tokens), 0) AS prompt_tokens,
    coalesce(sum(l.completion_tokens), 0) AS completion_tokens
  FROM public.ai_usage_log l
  WHERE public.is_admin(auth.uid())
    AND l.created_at >= now() - make_interval(days => greatest(_days, 1))
  GROUP BY 1, 2, 3
  ORDER BY 1 DESC, 4 DESC;
$$;

REVOKE ALL ON FUNCTION public.ai_usage_summary(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.ai_usage_summary(integer) TO authenticated, service_role;

-- Housekeeping: drop expired cache rows and usage older than 90 days, nightly.
DO $$
BEGIN
  PERFORM cron.unschedule('provider-cache-cleanup') WHERE EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'provider-cache-cleanup');
END $$;

SELECT cron.schedule(
  'provider-cache-cleanup',
  '40 3 * * *',
  $$
  DELETE FROM public.provider_cache WHERE expires_at < now();
  DELETE FROM public.ai_usage_log WHERE created_at < now() - interval '90 days';
  $$
);
